const express = require('express')
const cors = require('cors')
const multer = require('multer')
const path = require('node:path')
const HttpError = require('./utils/HttpError')
const authRoutes = require('./routes/authRoutes')
const vendorRoutes = require('./routes/vendorRoutes')
const adminVendorRoutes = require('./routes/adminVendorRoutes')
const adminCatalogRoutes = require('./routes/adminCatalogRoutes')
const vendorProductRoutes = require('./routes/vendorProductRoutes')
const publicMarketplaceRoutes = require('./routes/publicMarketplaceRoutes')
const orderRoutes = require('./routes/orderRoutes')
const vendorOrderRoutes = require('./routes/vendorOrderRoutes')
const adminOrderRoutes = require('./routes/adminOrderRoutes')
const paymentRoutes = require('./routes/paymentRoutes')
const adminDashboardRoutes = require('./routes/adminDashboardRoutes')
const vendorDashboardRoutes = require('./routes/vendorDashboardRoutes')
const customerDashboardRoutes = require('./routes/customerDashboardRoutes')
const reviewRoutes = require('./routes/reviewRoutes')

const app = express()
const allowedOrigins = (process.env.FRONTEND_ORIGIN || 'http://localhost:5173').split(',').map((origin) => origin.trim())
app.use(cors({ origin(origin, callback) {
  if (!origin || allowedOrigins.includes(origin)) return callback(null, true)
  return callback(new Error('Origin is not allowed by CORS.'))
} }))
app.use('/uploads', express.static(path.resolve(__dirname, '../uploads')))
app.use(express.json({ limit: '20kb' }))
app.get('/api/health', (req, res) => res.json({ status: 'ok' }))
app.use('/api/auth', authRoutes)
app.use('/api/customer', customerDashboardRoutes)
app.use('/api/orders', orderRoutes)
app.use('/api/payments', paymentRoutes)
app.use('/api/reviews', reviewRoutes)
app.use('/api/vendor/orders', vendorOrderRoutes)
app.use('/api/vendor/products', vendorProductRoutes)
app.use('/api/vendor/dashboard', vendorDashboardRoutes)
app.use('/api/vendor', vendorRoutes)
app.use('/api/admin/orders', adminOrderRoutes)
app.use('/api/admin/dashboard', adminDashboardRoutes)
app.use('/api/admin', adminCatalogRoutes)
app.use('/api/admin', adminVendorRoutes)
app.use('/api/public', publicMarketplaceRoutes)
app.use((req, res) => res.status(404).json({ message: 'Route not found.' }))
app.use((error, req, res, next) => {
  if (res.headersSent) return next(error)
  if (error.type === 'entity.parse.failed') return res.status(400).json({ message: 'Request body must be valid JSON.' })
  if (error.code === 'LIMIT_FILE_SIZE') return res.status(413).json({ message: 'Uploaded files must be 5 MB or smaller.' })
  if (error instanceof HttpError) return res.status(error.statusCode).json({ message: error.message, ...(error.errors ? { errors: error.errors } : {}) })
  if (error instanceof multer.MulterError) return res.status(400).json({ message: error.message || 'File upload error.' })
  if (error.message === 'Origin is not allowed by CORS.') return res.status(403).json({ message: error.message })
  if (error.code === 11000) return res.status(409).json({ message: 'A duplicate record already exists.', ...(error.keyValue ? { errors: error.keyValue } : {}) })
  console.error(error)
  return res.status(500).json({ message: 'An unexpected server error occurred.' })
})

module.exports = app
